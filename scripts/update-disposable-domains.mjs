#!/usr/bin/env node
// Refreshes functions/_lib/disposableDomains.generated.ts from the
// community-maintained blocklist at
// https://github.com/disposable-email-domains/disposable-email-domains
// Vendored (not an npm dep) so the sign-in path never runs code from a
// daily-republished third-party package. Run: node scripts/update-disposable-domains.mjs
import { writeFileSync } from 'node:fs';

const SRC =
  'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf';
const OUT = new URL('../functions/_lib/disposableDomains.generated.ts', import.meta.url);

const res = await fetch(SRC);
if (!res.ok) throw new Error(`HTTP ${res.status} fetching blocklist`);
const domains = [
  ...new Set(
    (await res.text())
      .split('\n')
      .map((l) => l.trim().toLowerCase())
      .filter((l) => l && !l.startsWith('#')),
  ),
].sort();

// Only plain hostnames — anything else would break the template literal.
const bad = domains.filter((d) => !/^[a-z0-9.-]+$/.test(d));
if (bad.length) throw new Error(`Unexpected entries: ${bad.slice(0, 5).join(', ')}`);
if (domains.length < 1000) throw new Error(`Suspiciously short list (${domains.length})`);

writeFileSync(
  OUT,
  `// GENERATED by scripts/update-disposable-domains.mjs — do not edit by hand.\n` +
    `// Source: ${SRC}\n` +
    `// ${domains.length} domains, fetched ${new Date().toISOString().slice(0, 10)}.\n` +
    `export const DISPOSABLE_DOMAINS_RAW = \`\n${domains.join('\n')}\n\`;\n`,
);
console.log(`Wrote ${domains.length} domains`);
